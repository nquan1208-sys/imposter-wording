import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const output = execFileSync('supabase', ['gen', 'types', '--local', '--schema', 'public'], {
  cwd: fileURLToPath(new URL('../../', import.meta.url)), encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'],
})
const source = ts.createSourceFile('database.ts', output, ts.ScriptTarget.Latest, true)
const formatted = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed }).printFile(source)
// Write only after generation succeeds, so CLI failures preserve the last valid types.
writeFileSync(new URL('../src/types/database.ts', import.meta.url), '// Generated by yarn types:database from the local public schema. Do not edit.\n' + formatted)
